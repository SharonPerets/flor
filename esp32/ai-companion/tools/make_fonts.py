#!/usr/bin/env python3
"""Makes src/gfont_data.cpp: smooth (anti-aliased) text for Gorgi's screen.

Run it again only if you want other sizes or letters:

    pip install pillow
    python tools/make_fonts.py path/to/Nunito[wght].ttf

The font is Nunito (c) The Nunito Project Authors, SIL Open Font License 1.1
(https://github.com/googlefonts/nunito).
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# name, pixel size, weight, characters ("ascii" = space to ~)
FONTS = [
    ("SUBTITLE", 26, 700, "ascii"),   # what Gorgi says
    ("TITLE", 22, 800, "ascii"),      # song title and clock
    ("SMALL", 16, 700, "ascii"),      # artist and status
    ("Z_BIG", 44, 800, "Z"),          # sleeping Zzz
    ("Z_SMALL", 30, 800, "Z"),
    ("BIG", 76, 800, "-0123456789"),  # the big temperature on the weather screen
    ("HEADLINE", 34, 800, "ascii"),   # song title on the music screen
]
GAMMA = 0.85  # a little extra weight on the edges: light text on dark looks thin otherwise


def chars_for(spec):
    """Every character from the first to the last one asked for (the table has no gaps)."""
    if spec == "ascii":
        return [chr(c) for c in range(32, 127)]
    codes = [ord(ch) for ch in spec]
    return [chr(c) for c in range(min(codes), max(codes) + 1)]


def make_font(path, name, size, weight, spec):
    font = ImageFont.truetype(path, size, layout_engine=ImageFont.Layout.BASIC)
    font.set_variation_by_axes([weight])
    ascent, descent = font.getmetrics()
    pad = size
    glyphs, alpha = [], bytearray()
    for ch in chars_for(spec):
        adv = font.getlength(ch)
        img = Image.new("L", (size * 3, size * 3), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if box is None:  # space
            glyphs.append((len(alpha), 0, 0, 0, 0, round(adv * 16)))
            continue
        crop = img.crop(box)
        w, h = crop.size
        data = bytes(round(255 * (v / 255) ** GAMMA) for v in crop.tobytes())
        glyphs.append((len(alpha), w, h, box[0] - pad, box[1] - (pad + ascent), round(adv * 16)))
        alpha += data
    return dict(name=name, first=ord(chars_for(spec)[0]), last=ord(chars_for(spec)[-1]), ascent=ascent,
                height=ascent + descent, glyphs=glyphs, alpha=alpha)


def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = ['// GENERATED by tools/make_fonts.py - do not edit by hand.',
           '// Font: Nunito (c) The Nunito Project Authors, SIL Open Font License 1.1.',
           '#include "gfont.h"', '', 'namespace gfont {', '']
    for spec in FONTS:
        f = make_font(sys.argv[1], *spec)
        n = f["name"]
        out.append(f'static const uint8_t {n}_ALPHA[] = {{')
        data = f["alpha"]
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f'static const Glyph {n}_GLYPHS[] = {{')
        for g in f["glyphs"]:
            out.append("  {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f'const Font {n} = {{{n}_GLYPHS, {n}_ALPHA, {f["first"]}, {f["last"]}, {f["ascent"]}, {f["height"]}}};')
        out.append("")
        print(f"{n}: {len(f['glyphs'])} glyphs, {len(data)} bytes, height {f['height']}", file=sys.stderr)
    out.append("}  // namespace gfont")
    dest = Path(__file__).resolve().parent.parent / "src" / "gfont_data.cpp"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest} ({dest.stat().st_size // 1024} KB)", file=sys.stderr)


if __name__ == "__main__":
    main()
