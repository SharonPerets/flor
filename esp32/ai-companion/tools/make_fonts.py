#!/usr/bin/env python3
"""Makes src/gfont_data.cpp: smooth (anti-aliased) text for Gorgi's screen.

Run it again only if you want other sizes or letters:

    pip install pillow
    python tools/make_fonts.py path/to/Nunito[wght].ttf
    python tools/make_fonts.py --hebrew path/to/Fredoka[wdth,wght].ttf   (-> src/gfont_hebrew.cpp)

The font is Nunito (c) The Nunito Project Authors, SIL Open Font License 1.1
(https://github.com/googlefonts/nunito). Hebrew letters come from Fredoka (c) The Fredoka
Project Authors, SIL Open Font License 1.1 (https://github.com/hafontia/Fredoka-One, see Fredoka-OFL.txt).
"""

import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont

# name, pixel size, weight, characters ("ascii" = space to ~)
FONTS = [
    ("SUBTITLE", 26, 700, "ascii"),   # what Gorgi says
    ("TITLE", 22, 800, "ascii"),      # song title and clock
    ("SMALL", 16, 700, "ascii"),      # artist and status
    ("Z_BIG", 44, 800, "Z"),          # sleeping Zzz
    ("Z_SMALL", 30, 800, "Z"),
    ("BIG", 76, 800, "-0123456789"),  # the big temperature on the weather screen
    ("HEADLINE", 34, 800, "ascii"),   # song title on the music screen
    ("NOTE", 21, 600, "ascii"),       # tasks on the To-do screen
]
# Hebrew letters (alef to tav) for the fonts that show text, from Fredoka. Fredoka looks heavier than
# Nunito at the same weight, so it is drawn 200 lighter.
HEBREW = [
    ("SUBTITLE", 26, 500),
    ("TITLE", 22, 600),
    ("SMALL", 16, 500),
    ("HEADLINE", 34, 600),
    ("NOTE", 21, 400),
]
HEBREW_CHARS = "".join(chr(c) for c in range(0x05D0, 0x05EB))
GAMMA = 0.85  # a little extra weight on the edges: light text on dark looks thin otherwise


def chars_for(spec):
    """Every character from the first to the last one asked for (the table has no gaps)."""
    if spec == "ascii":
        return [chr(c) for c in range(32, 127)]
    if spec == "hebrew":
        return list(HEBREW_CHARS)
    codes = [ord(ch) for ch in spec]
    return [chr(c) for c in range(min(codes), max(codes) + 1)]


def set_weight(font, weight):
    """Sets the weight axis (and leaves other axes, like width, at their default)."""
    axes = font.get_variation_axes()
    font.set_variation_by_axes([weight if b"eight" in bytes(a["name"]) else a["default"] for a in axes])


def make_font(path, name, size, weight, spec):
    font = ImageFont.truetype(path, size, layout_engine=ImageFont.Layout.BASIC)
    set_weight(font, weight)
    ascent, descent = font.getmetrics()
    pad = size
    glyphs, alpha = [], bytearray()
    for ch in chars_for(spec):
        adv = font.getlength(ch)
        img = Image.new("L", (size * 3, size * 3), 0)
        ImageDraw.Draw(img).text((pad, pad + ascent), ch, font=font, fill=255, anchor="ls")
        box = img.getbbox()
        if box is None:  # space
            glyphs.append((len(alpha), 0, 0, 0, 0, round(adv * 16)))
            continue
        crop = img.crop(box)
        w, h = crop.size
        data = bytes(round(255 * (v / 255) ** GAMMA) for v in crop.tobytes())
        glyphs.append((len(alpha), w, h, box[0] - pad, box[1] - (pad + ascent), round(adv * 16)))
        alpha += data
    return dict(name=name, first=ord(chars_for(spec)[0]), last=ord(chars_for(spec)[-1]), ascent=ascent,
                height=ascent + descent, glyphs=glyphs, alpha=alpha)


def main_hebrew(path):
    out = ['// GENERATED by tools/make_fonts.py --hebrew - do not edit by hand.',
           '// Hebrew letters from Fredoka (c) The Fredoka Project Authors, SIL Open Font License 1.1.',
           '#include "gfont.h"', '', 'namespace gfont {', '']
    for name, size, weight in HEBREW:
        f = make_font(path, name, size, weight, "hebrew")
        out.append(f'static const uint8_t {name}_HEB_ALPHA[] = {{')
        data = f["alpha"]
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f'static const Glyph {name}_HEB_GLYPHS[] = {{')
        for g in f["glyphs"]:
            out.append("  {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f'static const Extra {name}_HEB = {{{name}_HEB_GLYPHS, {name}_HEB_ALPHA, {f["first"]}, {f["last"]}}};')
        out.append("")
        print(f"{name} (Hebrew): {len(f['glyphs'])} glyphs, {len(data)} bytes", file=sys.stderr)
    out.append("const Extra* extraFor(const Font& f) {")
    for name, _, _ in HEBREW:
        out.append(f"  if (&f == &{name}) return &{name}_HEB;")
    out.append("  return nullptr;")
    out.append("}")
    out.append("")
    out.append("}  // namespace gfont")
    dest = Path(__file__).resolve().parent.parent / "src" / "gfont_hebrew.cpp"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest} ({dest.stat().st_size // 1024} KB)", file=sys.stderr)


def main():
    if len(sys.argv) == 3 and sys.argv[1] == "--hebrew":
        return main_hebrew(sys.argv[2])
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    out = ['// GENERATED by tools/make_fonts.py - do not edit by hand.',
           '// Font: Nunito (c) The Nunito Project Authors, SIL Open Font License 1.1.',
           '#include "gfont.h"', '', 'namespace gfont {', '']
    for spec in FONTS:
        f = make_font(sys.argv[1], *spec)
        n = f["name"]
        out.append(f'static const uint8_t {n}_ALPHA[] = {{')
        data = f["alpha"]
        for i in range(0, len(data), 24):
            out.append("  " + ",".join(str(b) for b in data[i:i + 24]) + ",")
        out.append("};")
        out.append(f'static const Glyph {n}_GLYPHS[] = {{')
        for g in f["glyphs"]:
            out.append("  {%d,%d,%d,%d,%d,%d}," % g)
        out.append("};")
        out.append(f'const Font {n} = {{{n}_GLYPHS, {n}_ALPHA, {f["first"]}, {f["last"]}, {f["ascent"]}, {f["height"]}}};')
        out.append("")
        print(f"{n}: {len(f['glyphs'])} glyphs, {len(data)} bytes, height {f['height']}", file=sys.stderr)
    out.append("}  // namespace gfont")
    dest = Path(__file__).resolve().parent.parent / "src" / "gfont_data.cpp"
    dest.write_text("\n".join(out) + "\n")
    print(f"wrote {dest} ({dest.stat().st_size // 1024} KB)", file=sys.stderr)


if __name__ == "__main__":
    main()
